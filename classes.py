
class Dog:
    def __init__(self, name, breed):
        self.name = name
        self.breed = breed

class Cat:
    def __init__(self, name, breed):
        self.name = name
        self.breed = breed

modi = Dog("Modi", "Coward")
gyanesh = Cat("Gyanesh", "Zatu")

print(modi.name)
print(modi.breed)

print(gyanesh.name)
print(gyanesh.breed)
